"""
Writes the package manager manifests of a release of ChainShot.exe:

  bucket/chainshot.json                                   Scoop (this repository is the bucket)
  packaging/winget/manifests/d/Dalkin69/ChainShot/<v>/   winget (submitted to microsoft/winget-pkgs)

    python packaging/update_manifests.py 1.3.0 <sha256 of chainshot-app-v1.3.0.zip> [--date 2026-10-18]

Run by the release workflow with the hash from SHA256SUMS.txt.
"""
import argparse
import datetime as dt
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPO = "https://github.com/Dalkin69/chainshot"
ID = "Dalkin69.ChainShot"
SHORT = "Timestamped, hash-chained forensic screenshots and evidence journal"
DESCRIPTION = (
    "ChainShot takes screenshots for forensic and investigation reports: a banner below the image "
    "(case, tag, UTC time, examiner), SHA-256 of every file, an append-only hash-chained journal, seals "
    "with RFC 3161 timestamps, HTML report and evidence packages that anyone can verify with Python. "
    "Global hotkeys, tray icon, browser extension link. No telemetry."
)


def url(version: str) -> str:
    return f"{REPO}/releases/download/v{version}/chainshot-app-v{version}.zip"


def scoop(version: str, sha256: str) -> dict:
    return {
        "version": version,
        "description": SHORT + ".",
        "homepage": REPO,
        "license": "MIT",
        "notes": "Case folders are yours: 'scoop uninstall chainshot' never touches them.",
        "url": url(version),
        "hash": sha256.lower(),
        "bin": [["ChainShot.exe", "chainshot"]],
        "shortcuts": [["ChainShot.exe", "ChainShot"]],
        # Remove what the app registered (start with Windows, browser link); keep settings on update.
        "pre_uninstall": "if ($cmd -eq 'uninstall') { & \"$dir\\ChainShot.exe\" uninstall --keep-settings | Out-Null }",
        "checkver": "github",
        "autoupdate": {"url": f"{REPO}/releases/download/v$version/chainshot-app-v$version.zip"},
    }


def winget(version: str, sha256: str, date: str) -> dict:
    head = "# Generated by packaging/update_manifests.py\n# yaml-language-server: $schema=https://aka.ms/winget-manifest.{kind}.1.6.0.schema.json\n"
    common = f"PackageIdentifier: {ID}\nPackageVersion: {version}\n"
    return {
        f"{ID}.yaml": head.format(kind="version") + common + "DefaultLocale: en-US\nManifestType: version\nManifestVersion: 1.6.0\n",
        f"{ID}.installer.yaml": head.format(kind="installer") + common + f"""InstallerType: zip
NestedInstallerType: portable
NestedInstallerFiles:
  - RelativeFilePath: ChainShot.exe
    PortableCommandAlias: chainshot
UpgradeBehavior: uninstallPrevious
ReleaseDate: {date}
Installers:
  - Architecture: neutral
    InstallerUrl: {url(version)}
    InstallerSha256: {sha256.upper()}
ManifestType: installer
ManifestVersion: 1.6.0
""",
        f"{ID}.locale.en-US.yaml": head.format(kind="defaultLocale") + common + f"""PackageLocale: en-US
Publisher: Dalkin69
PublisherUrl: https://github.com/Dalkin69
PublisherSupportUrl: {REPO}/issues
PrivacyUrl: https://dalkin69.github.io/chainshot/privacy.html
Author: Dalkin69
PackageName: ChainShot
PackageUrl: {REPO}
License: MIT
LicenseUrl: {REPO}/blob/main/LICENSE
ShortDescription: {json.dumps(SHORT)}
Description: {json.dumps(DESCRIPTION)}
Moniker: chainshot
Tags:
  - forensics
  - dfir
  - screenshot
  - evidence
  - sha256
  - chain-of-custody
ReleaseNotesUrl: {REPO}/releases/tag/v{version}
ManifestType: defaultLocale
ManifestVersion: 1.6.0
""",
    }


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("version")
    ap.add_argument("sha256")
    ap.add_argument("--date", default=dt.date.today().isoformat())
    ap.add_argument("--root", default=str(ROOT), help="output root (tests)")
    a = ap.parse_args()
    version = a.version.lstrip("v")
    if not re.fullmatch(r"\d+\.\d+\.\d+", version) or not re.fullmatch(r"[0-9a-fA-F]{64}", a.sha256):
        raise SystemExit("usage: update_manifests.py <x.y.z> <sha256>")
    root = Path(a.root)
    (root / "bucket").mkdir(parents=True, exist_ok=True)
    (root / "bucket" / "chainshot.json").write_text(json.dumps(scoop(version, a.sha256), indent=4) + "\n", encoding="utf-8")
    wdir = root / "packaging" / "winget" / "manifests" / "d" / "Dalkin69" / "ChainShot" / version
    wdir.mkdir(parents=True, exist_ok=True)
    for name, text in winget(version, a.sha256, a.date).items():
        (wdir / name).write_text(text, encoding="utf-8")
    print(f"Scoop: {root / 'bucket' / 'chainshot.json'}\nwinget: {wdir}")


if __name__ == "__main__":
    main()
