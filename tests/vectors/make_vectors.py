"""
Generate tests/vectors/canonical-vectors.json from the reference implementation.

The vectors are the cross-language contract: the PowerShell module and the
browser extension must compute exactly the same entry hashes and chain values.
Run from the repository root:  python tests/vectors/make_vectors.py
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "python"))
import chainshot as cs  # noqa: E402

ENTRIES = [
    {"v": "1", "seq": "1", "utc": "2026-10-16T08:00:00.000Z", "type": "note", "tag": "INIT",
     "file": "", "size": "", "sha256": "", "examiner": "Louis", "host": "LAB-PC",
     "source": "chainshot-py/1.0.0", "url": "", "title": "", "note": "Case created: TP"},
    {"v": "1", "seq": "2", "utc": "2026-10-16T08:01:02.345Z", "type": "screenshot", "tag": "P17",
     "file": "captures/0002_20261016T080102Z_P17.png", "size": "123456",
     "sha256": "a" * 64, "examiner": "Louis", "host": "LAB-PC", "source": "chainshot-ps/1.0.0",
     "url": "", "title": "", "note": "Évidence: \"quoted\" \\ back\\slash \t tab"},
    {"v": "1", "seq": "3", "utc": "2026-10-16T08:02:00.000Z", "type": "browser", "tag": "P22",
     "file": "captures/0003_20261016T080200Z_P22.png", "size": "42", "sha256": "b" * 64,
     "examiner": "Louis", "host": "", "source": "chainshot-ext/1.0.0",
     "url": "https://example.org/path?q=1&r=été", "title": "Page — 📸 test",
     "note": "line1\r\nline2\nline3\rend"},
]


def main() -> None:
    prev, out = cs.GENESIS, []
    for e in ENTRIES:
        chain = cs.next_chain(prev, e)
        out.append({"entry": e, "canonical": cs.canonical_string(e), "entry_hash": cs.entry_hash(e), "chain": chain})
        prev = chain
    doc = {"description": "ChainShot v1 canonical vectors. Generated by make_vectors.py; do not edit.",
           "genesis": cs.GENESIS, "fields": list(cs.CHAINED_FIELDS), "vectors": out}
    target = Path(__file__).with_name("canonical-vectors.json")
    target.write_text(json.dumps(doc, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"written {target}")


if __name__ == "__main__":
    main()
